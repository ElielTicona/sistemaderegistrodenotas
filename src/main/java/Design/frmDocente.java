    private void instalarMenuImpresos() {
        if (docenteLogueado == null || !"DOCENTE".equals(docenteLogueado.getRol())) return;
        javax.swing.JMenuBar barra = getJMenuBar();
        if (barra == null) barra = new javax.swing.JMenuBar();
        javax.swing.JMenu menu = new javax.swing.JMenu("EXAMENES IMPRESOS");
        javax.swing.JMenuItem abrir = new javax.swing.JMenuItem("Generar PDF, QR y escanear hojas");
        abrir.setAccelerator(javax.swing.KeyStroke.getKeyStroke("control I"));
        abrir.addActionListener(evento -> new Impresos.PantallaImpresos(this, docenteLogueado.getId_usuario()).setVisible(true));
        menu.add(abrir);
        barra.add(menu);
        setJMenuBar(barra);
    }

