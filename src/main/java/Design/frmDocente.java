    private void actualizarContadores() {
        int idProfe = docenteLogueado.getId_usuario();

        String sqlCursos = "SELECT COUNT(*) FROM cursos WHERE id_docente = ? AND estado = 1";
        
        String sqlAlumnos = "SELECT COUNT(DISTINCT m.dni_estudiante) " +
                            "FROM matricula m " +
                            "INNER JOIN cursos c ON m.id_curso = c.id_curso " +
                            "WHERE c.id_docente = ? AND c.estado = 1";

        String sqlUsuarios = "SELECT COUNT(*) FROM usuarios WHERE estado = 1";

        try (java.sql.Connection cn = Conexion.Conexion.conectar()) {
            
            try (java.sql.PreparedStatement pst1 = cn.prepareStatement(sqlCursos)) {
                pst1.setInt(1, idProfe);
                java.sql.ResultSet rs1 = pst1.executeQuery();
                if (rs1.next()) lblTotCursos.setText(String.format("%02d", rs1.getInt(1)));
            }

            try (java.sql.PreparedStatement pst2 = cn.prepareStatement(sqlAlumnos)) {
                pst2.setInt(1, idProfe);
                java.sql.ResultSet rs2 = pst2.executeQuery();
                if (rs2.next()) lblTotEst.setText(String.format("%02d", rs2.getInt(1)));
            }

            try (java.sql.Statement st = cn.createStatement();
                 java.sql.ResultSet rs3 = st.executeQuery(sqlUsuarios)) {
                if (rs3.next()) lblTotUsu.setText(String.format("%02d", rs3.getInt(1)));
            }

        } catch (Exception e) {
            System.out.println("Error al cargar contadores del Docente: " + e.getMessage());
        }
    }
    
