    private void cargarTablaCursos(String filtro) {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID CURSO");
        modelo.addColumn("NOMBRE DEL CURSO");
        modelo.addColumn("SEMESTRE");
        tblCursos.setModel(modelo); 
        tblCursos.getColumnModel().getColumn(0).setMaxWidth(0);
        tblCursos.getColumnModel().getColumn(0).setMinWidth(0);
        tblCursos.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);

        String sql = "SELECT id_curso, nombre_curso, semestre FROM cursos "
                   + "WHERE id_docente = ? AND nombre_curso LIKE ? AND estado = 1";

        try (java.sql.Connection cn = Conexion.Conexion.conectar();
             java.sql.PreparedStatement pst = cn.prepareStatement(sql)) {

            pst.setInt(1, idDocenteActivo);
            pst.setString(2, "%" + filtro + "%");
            java.sql.ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt(1),
                    rs.getString(2),
                    rs.getString(3)
                });
            }
        } catch (Exception e) {
            System.out.println("Error al cargar mis cursos: " + e.getMessage());
        }
    }
