    private void txtSubirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSubirActionPerformed
        String ruta = txtRuta.getText().trim();
        
        if (ruta.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un archivo de Excel antes de subir.");
            return;
        }
        Ctrl_Estudiante ctrl = new Ctrl_Estudiante();

        int[] resultados = ctrl.importarExcel(ruta);

        JOptionPane.showMessageDialog(this, 
            "Proceso terminado.\n" +
            "Estudiantes registrados: " + resultados[0] + "\n" +
            "Errores o Duplicados: " + resultados[1] + "\n\n" +
            "Nota: Se usó el Código como Usuario y Password.");

        cargarTabla("");
        txtRuta.setText("");
        estadoInicial();
    }//GEN-LAST:event_txtSubirActionPerformed

