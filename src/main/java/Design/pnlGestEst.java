    private void estadoInicial() {
        dniSeleccionado = "";
        limpiarCampos();
        btnGuardar.setEnabled(true);  
        btnEdit.setEnabled(false);    
        btnElim.setEnabled(false);    
        txtCod.requestFocus();
    }

    private void limpiarCampos() {
        txtCod.setText("");
        txtApeyNom.setText("");
        cboEscPro.setSelectedIndex(0);
        cboSem.setSelectedIndex(0);
        txtUser.setText("");
        txtPass.setText("");
    }

    private void cargarTabla(String valor) {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("COD. UNIV");
        modelo.addColumn("DNI");
        modelo.addColumn("NOMBRES");
        modelo.addColumn("ID_ESC");
        modelo.addColumn("SEMESTRE");
        tblEst.setModel(modelo);
        tblEst.getColumnModel().getColumn(3).setMaxWidth(0);
        tblEst.getColumnModel().getColumn(3).setMinWidth(0);
        tblEst.getTableHeader().getColumnModel().getColumn(3).setMaxWidth(0);

        Ctrl_Estudiante ctrl = new Ctrl_Estudiante();
        List<Estudiante> lista = ctrl.listarEstudiantes(valor); 

        for (Estudiante e : lista) {
            modelo.addRow(new Object[]{
                e.getCodigo_univ(),
                e.getDni(),
                e.getNombre_completo(),
                e.getId_escuela(), 
                e.getSemestre()
            });
        }
    }
    
    private void cargarCombos() {
        listaIdEscuelas.clear();
        cboEscPro.removeAllItems();
        cboEscPro.addItem("Seleccione Escuela...");
        listaIdEscuelas.add(0);

        try (java.sql.Connection cn = Conexion.Conexion.conectar();
             java.sql.Statement st = cn.createStatement();
             java.sql.ResultSet rsE = st.executeQuery("SELECT id_escuela, nombre_escuela FROM escuelas WHERE estado = 1")) {
            
            while (rsE.next()) {
                cboEscPro.addItem(rsE.getString("nombre_escuela"));
                listaIdEscuelas.add(rsE.getInt("id_escuela"));
            }
        } catch (Exception e) {
            System.out.println("Error al cargar combo de escuelas en estudiantes: " + e.getMessage());
        }
    }
