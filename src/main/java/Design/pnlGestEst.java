    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtCod.getText().isEmpty() || txtApeyNom.getText().isEmpty() || cboEscPro.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this, "Debe completar los campos");
            return;
        }
        Constructores.Estudiante est = new Constructores.Estudiante();
        String codigo = txtCod.getText().trim();

        est.setCodigo_univ(codigo);
        est.setDni(codigo); 
        est.setNombre_completo(txtApeyNom.getText().trim().toUpperCase());
        est.setId_escuela(listaIdEscuelas.get(cboEscPro.getSelectedIndex()));
        est.setSemestre(cboSem.getSelectedItem().toString());

        if (new Controladores.Ctrl_Estudiante().guardar(est)) {
            JOptionPane.showMessageDialog(this, "Estudiante registrado con éxito");
            cargarTabla("");
            estadoInicial();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (cboEscPro.getSelectedIndex() <= 0) {
             JOptionPane.showMessageDialog(this, "Seleccione una escuela válida");
             return;
        }
        Ctrl_Estudiante ctrl = new Ctrl_Estudiante();
        Estudiante est = new Estudiante();

        est.setDni(dniSeleccionado);
        est.setNombre_completo(txtApeyNom.getText().toUpperCase());
        est.setId_escuela(listaIdEscuelas.get(cboEscPro.getSelectedIndex()));
        est.setSemestre(cboSem.getSelectedItem().toString());

        if (ctrl.actualizar(est)) {
            JOptionPane.showMessageDialog(this, "Registro actualizado con éxito");
            cargarTabla("");
            estadoInicial();
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void tblEstMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEstMouseClicked
        int fila = tblEst.getSelectedRow();
        if (fila >= 0) {
            String cod = tblEst.getValueAt(fila, 0).toString();
            dniSeleccionado = tblEst.getValueAt(fila, 1).toString();
            String nombres = tblEst.getValueAt(fila, 2).toString();
            String idEsc = tblEst.getValueAt(fila, 3).toString();
            String sem = tblEst.getValueAt(fila, 4).toString();

            txtCod.setText(cod);
            txtUser.setText(dniSeleccionado);
            txtPass.setText(dniSeleccionado); 
            txtApeyNom.setText(nombres);
            int idEscuelaBD = Integer.parseInt(idEsc);
            int indexCombo = listaIdEscuelas.indexOf(idEscuelaBD);
            if(indexCombo != -1) {
                cboEscPro.setSelectedIndex(indexCombo);
            }
            cboSem.setSelectedItem(sem); 

            btnGuardar.setEnabled(false);
            btnEdit.setEnabled(true);
            btnElim.setEnabled(true);
            
        }
    }//GEN-LAST:event_tblEstMouseClicked

    private void btnElimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnElimActionPerformed
        if (dniSeleccionado.isEmpty()) return;

        int r = JOptionPane.showConfirmDialog(this, "¿Eliminar al estudiante con código " + dniSeleccionado + "?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (r == JOptionPane.YES_OPTION) {
            if (new Ctrl_Estudiante().eliminar(dniSeleccionado)) {
                JOptionPane.showMessageDialog(this, "Estudiante dado de baja.");
                cargarTabla("");
                estadoInicial();
            }
        }
    }//GEN-LAST:event_btnElimActionPerformed

