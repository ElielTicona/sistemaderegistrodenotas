    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed

        String user = txtUsuario.getText().trim();
        String pass = new String(txtPass.getPassword());

        if (!user.isEmpty() && !pass.isEmpty()) {
            Ctrl_Usuario control = new Ctrl_Usuario();
            Usuario auth = control.login(user, pass);

            if (auth != null) {
                this.dispose();

                switch (auth.getRol()) {
                    case "ADMIN":
                        new frmAdmin().setVisible(true);
                        break;
                    case "DOCENTE":
                        new frmDocente(auth).setVisible(true); 
                        break;
                    case "ESTUDIANTE":
                        new frmEstudiantes(auth).setVisible(true);
                        break;
                }
            } else {
                JOptionPane.showMessageDialog(null, "Acceso denegado. Verifique sus credenciales.");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Ingrese usuario y contraseña.");
        }
    
    }//GEN-LAST:event_jButton7ActionPerformed

