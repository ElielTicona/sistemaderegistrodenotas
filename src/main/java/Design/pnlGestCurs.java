    private void estadoInicial() {
        idCursoSeleccionado = 0;
        txtNomCurso.setText("");
        bcoDoc.setSelectedIndex(0);
        bcoEP.setSelectedIndex(0);
        cboSeme.setSelectedIndex(0);
        btnGuardar.setEnabled(true);
        btnEditar.setEnabled(false);
        btnElim.setEnabled(false);
    }

    private void cargarCombos() {
        listaIdDocentes.clear();
        listaIdEscuelas.clear();
        bcoDoc.removeAllItems();
        bcoEP.removeAllItems();

        bcoDoc.addItem("Seleccione Docente...");
        listaIdDocentes.add(0);
        bcoEP.addItem("Seleccione Escuela...");
        listaIdEscuelas.add(0);

        try (Connection cn = Conexion.conectar()) {
            ResultSet rsD = cn.createStatement().executeQuery("SELECT id_usuario, nombre_completo FROM usuarios WHERE rol = 'DOCENTE'");
            while (rsD.next()) {
                bcoDoc.addItem(rsD.getString(2));
                listaIdDocentes.add(rsD.getInt(1));
            }
            ResultSet rsE = cn.createStatement().executeQuery("SELECT id_escuela, nombre_escuela FROM escuelas");
            while (rsE.next()) {
                bcoEP.addItem(rsE.getString(2));
                listaIdEscuelas.add(rsE.getInt(1));
            }
        } catch (Exception e) { System.out.println(e); }
    }

    private void cargarTabla(String valor) {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("CURSO");
        modelo.addColumn("DOCENTE");
        modelo.addColumn("ESCUELA");
        modelo.addColumn("SEM");
        tblCursos.setModel(modelo);
        tblCursos.getColumnModel().getColumn(0).setMaxWidth(0);
        tblCursos.getColumnModel().getColumn(0).setMinWidth(0);
        tblCursos.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);

        List<Object[]> lista = new Ctrl_Curso().listarCursosTabla(valor);
        for (Object[] fila : lista) { modelo.addRow(fila); }
    }
