    private void btnFinalizaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizaActionPerformed
        guardarRespuestaTemporal();
        if (respuestasAlumno.size() < listaPreguntas.size()) {
            int confirm = JOptionPane.showConfirmDialog(this,
                "Te faltan responder algunas preguntas. ¿Estás seguro de que deseas enviar el examen incompleto?",
                "Confirmar entrega", JOptionPane.YES_NO_OPTION);
            if (confirm != JOptionPane.YES_OPTION) return; 
        } else {
            int confirm = JOptionPane.showConfirmDialog(this,
                "¿Confirmas el envío definitivo del examen?",
                "Confirmar entrega", JOptionPane.YES_NO_OPTION);
            if (confirm != JOptionPane.YES_OPTION) return;
        }

        Ctrl_Resultado ctrlResultado = new Ctrl_Resultado();
        boolean exito = ctrlResultado.calificarExamen(dniEstudianteActivo, idEvaluacionActiva, respuestasAlumno);

        if (exito) {
            JOptionPane.showMessageDialog(this, "¡Examen finalizado con éxito!");
            
            cargarResultadosEstudiante(); 
            respuestasAlumno.clear();
            if (listaPreguntas != null) listaPreguntas.clear();
            idEvaluacionActiva = 0;
            indicePreguntaActual = 0;
            jTabbedPane4.setSelectedIndex(0); 
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error en la base de datos al calificar.");
        }
    }//GEN-LAST:event_btnFinalizaActionPerformed

    private void btnSigActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSigActionPerformed
        guardarRespuestaTemporal();
        if (indicePreguntaActual < listaPreguntas.size() - 1) {
            indicePreguntaActual++;
            mostrarPreguntaActual();
        }
    }//GEN-LAST:event_btnSigActionPerformed

    private void btnAtrasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtrasActionPerformed
        guardarRespuestaTemporal();
        if (indicePreguntaActual > 0) {
            indicePreguntaActual--;
            mostrarPreguntaActual();
        }
    }//GEN-LAST:event_btnAtrasActionPerformed

    private void btnIngreEvaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngreEvaActionPerformed
        int fila = tblEvaAlum.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una evaluación de la tabla para iniciar.");
            return;
        }

        idEvaluacionActiva = Integer.parseInt(tblEvaAlum.getValueAt(fila, 0).toString());
        
        Ctrl_Pregunta ctrlPreg = new Ctrl_Pregunta();
        listaPreguntas = ctrlPreg.listarPreguntasPorEvaluacion(idEvaluacionActiva);
        if (listaPreguntas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Esta evaluación aún no tiene preguntas configuradas.");
            return;
        }
        indicePreguntaActual = 0;
        respuestasAlumno.clear();
        mostrarPreguntaActual();
        jTabbedPane4.setSelectedIndex(1);
    }//GEN-LAST:event_btnIngreEvaActionPerformed

