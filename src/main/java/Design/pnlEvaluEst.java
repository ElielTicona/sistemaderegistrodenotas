    private void guardarRespuestaTemporal() {
        if (listaPreguntas == null || listaPreguntas.isEmpty() || opcionesActuales == null) return;

        int idPreguntaActual = listaPreguntas.get(indicePreguntaActual).getId_pregunta();
        int idOpcionSeleccionada = -1;

        if (spinPregA.isSelected() && opcionesActuales.size() > 0) idOpcionSeleccionada = opcionesActuales.get(0).getId_opcion();
        if (spinPregB.isSelected() && opcionesActuales.size() > 1) idOpcionSeleccionada = opcionesActuales.get(1).getId_opcion();
        if (spinPregC.isSelected() && opcionesActuales.size() > 2) idOpcionSeleccionada = opcionesActuales.get(2).getId_opcion();
        if (spinPregD.isSelected() && opcionesActuales.size() > 3) idOpcionSeleccionada = opcionesActuales.get(3).getId_opcion();

        if (idOpcionSeleccionada != -1) {
            respuestasAlumno.put(idPreguntaActual, idOpcionSeleccionada);
        }
    }

    private void mostrarPreguntaActual() {
        if (listaPreguntas == null || listaPreguntas.isEmpty()) return;

        Pregunta preguntaActual = listaPreguntas.get(indicePreguntaActual);
        lblPregun.setText("<html>" + (indicePreguntaActual + 1) + ". " + preguntaActual.getTexto_pregunta() + "</html>"); // HTML para multilinea

        Ctrl_Pregunta ctrlPreg = new Ctrl_Pregunta();
        opcionesActuales = ctrlPreg.listarOpcionesPorPregunta(preguntaActual.getId_pregunta());
        buttonGroup1.clearSelection();
        spinPregA.setVisible(false); spinPregB.setVisible(false);
        spinPregC.setVisible(false); spinPregD.setVisible(false);

        if (opcionesActuales.size() > 0) { spinPregA.setText(opcionesActuales.get(0).getTexto_opcion()); spinPregA.setVisible(true); }
        if (opcionesActuales.size() > 1) { spinPregB.setText(opcionesActuales.get(1).getTexto_opcion()); spinPregB.setVisible(true); }
        if (opcionesActuales.size() > 2) { spinPregC.setText(opcionesActuales.get(2).getTexto_opcion()); spinPregC.setVisible(true); }
        if (opcionesActuales.size() > 3) { spinPregD.setText(opcionesActuales.get(3).getTexto_opcion()); spinPregD.setVisible(true); }
        if (respuestasAlumno.containsKey(preguntaActual.getId_pregunta())) {
            int idOpcionGuardada = respuestasAlumno.get(preguntaActual.getId_pregunta());
            if (opcionesActuales.size() > 0 && opcionesActuales.get(0).getId_opcion() == idOpcionGuardada) spinPregA.setSelected(true);
            if (opcionesActuales.size() > 1 && opcionesActuales.get(1).getId_opcion() == idOpcionGuardada) spinPregB.setSelected(true);
            if (opcionesActuales.size() > 2 && opcionesActuales.get(2).getId_opcion() == idOpcionGuardada) spinPregC.setSelected(true);
            if (opcionesActuales.size() > 3 && opcionesActuales.get(3).getId_opcion() == idOpcionGuardada) spinPregD.setSelected(true);
        }

        btnAtras.setEnabled(indicePreguntaActual > 0);
        
        if (indicePreguntaActual == listaPreguntas.size() - 1) {
            btnSig.setEnabled(false);
            btnFinaliza.setEnabled(true);
        } else {
            btnSig.setEnabled(true);
            btnFinaliza.setEnabled(false); 
        }
    }
    
    private void listarEvaluacionesDisponibles() {
        DefaultTableModel modelo = (DefaultTableModel) tblEvaAlum.getModel();
        modelo.setRowCount(0); 
        Ctrl_Evaluacion ctrlEval = new Ctrl_Evaluacion();
        java.util.List<Evaluacion> lista = ctrlEval.listarPorCurso(idCursoSeleccionado);
        
        for (Evaluacion ev : lista) {
            if(ev.getTipo().equalsIgnoreCase("EXAMEN")) {
                modelo.addRow(new Object[]{
                    ev.getId_evaluacion(),
                    ev.getTitulo(),
                    ev.getTipo(),
                    ev.getFecha_examen()
                });
            }
        }
    }
    
    private void cargarResultadosEstudiante() {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
            new Object [][] {},
            new String [] {"EVALUACIÓN", "TIPO", "NOTA OBTENIDA", "FECHA"}
        );
        tblResul.setModel(modelo);

        Controladores.Ctrl_Resultado ctrlRes = new Controladores.Ctrl_Resultado();
        java.util.List<Object[]> notas = ctrlRes.listarNotasEstudiante(dniEstudianteActivo, idCursoSeleccionado);

        for (Object[] fila : notas) {
            modelo.addRow(fila);
        }
    }
