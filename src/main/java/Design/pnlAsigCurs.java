    private void cargarCombos() {
        listaIdCursos.clear();
        listaIdEscuelas.clear();
        cboCurso.removeAllItems();
        cboEscPro.removeAllItems();

        cboCurso.addItem("Seleccione Curso...");
        listaIdCursos.add(0);
        cboEscPro.addItem("Seleccione Escuela...");
        listaIdEscuelas.add(0);

        try (java.sql.Connection cn = Conexion.Conexion.conectar()) {
            java.sql.ResultSet rsC = cn.createStatement().executeQuery("SELECT id_curso, nombre_curso FROM cursos WHERE estado = 1");
            while (rsC.next()) {
                cboCurso.addItem(rsC.getString(2));
                listaIdCursos.add(rsC.getInt(1));
            }
            java.sql.ResultSet rsE = cn.createStatement().executeQuery("SELECT id_escuela, nombre_escuela FROM escuelas");
            while (rsE.next()) {
                cboEscPro.addItem(rsE.getString(2));
                listaIdEscuelas.add(rsE.getInt(1));
            }
        } catch (Exception e) {
            System.out.println("Error al cargar combos: " + e);
        }
    }

    private void actualizarTablas() {
        if (listaIdCursos.isEmpty() || listaIdEscuelas.isEmpty()) {
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0 || cboEscPro.getSelectedIndex() <= 0) {
            return; 
        }

        int idCurso = listaIdCursos.get(cboCurso.getSelectedIndex());
        int idEscuela = listaIdEscuelas.get(cboEscPro.getSelectedIndex());
        String semestre = cboSem.getSelectedItem().toString(); 

        Controladores.Ctrl_Curso ctrl = new Controladores.Ctrl_Curso();

        DefaultTableModel modIzq = new DefaultTableModel();
        modIzq.addColumn("CÓDIGO");
        modIzq.addColumn("ESTUDIANTE");
        tblPorAsignar.setModel(modIzq);
        
        List<Object[]> disp = ctrl.listarEstudiantesDisponibles(idEscuela, semestre, idCurso);
        for (Object[] fila : disp) { modIzq.addRow(fila); }

        DefaultTableModel modDer = new DefaultTableModel();
        modDer.addColumn("CÓDIGO");
        modDer.addColumn("ESTUDIANTE");
        tblAsig.setModel(modDer);
        
        List<Object[]> asig = ctrl.listarAsignados(idCurso);
        for (Object[] fila : asig) { modDer.addRow(fila); }
    }

