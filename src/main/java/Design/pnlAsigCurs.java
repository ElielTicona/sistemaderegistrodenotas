    private void btnAsigTodosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAsigTodosActionPerformed
        if (tblPorAsignar.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No hay estudiantes para asignar.");
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0) return;

        int idCurso = listaIdCursos.get(cboCurso.getSelectedIndex());
        Controladores.Ctrl_Curso ctrl = new Controladores.Ctrl_Curso();
        
        int exitos = 0;
        for (int i = 0; i < tblPorAsignar.getRowCount(); i++) {
            String codigo = tblPorAsignar.getValueAt(i, 0).toString();
            if (ctrl.asignarEstudiante(idCurso, codigo)) {
                exitos++;
            }
        }
        JOptionPane.showMessageDialog(this, "Se asignaron " + exitos + " estudiantes al curso.");
        actualizarTablas();
    }//GEN-LAST:event_btnAsigTodosActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        int fila = tblPorAsignar.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un estudiante de la tabla izquierda.");
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0) return;

        int idCurso = listaIdCursos.get(cboCurso.getSelectedIndex());
        String codigoEstudiante = tblPorAsignar.getValueAt(fila, 0).toString();

        if (new Controladores.Ctrl_Curso().asignarEstudiante(idCurso, codigoEstudiante)) {
            actualizarTablas();
        } else {
            JOptionPane.showMessageDialog(this, "Error al asignar.");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        int fila = tblAsig.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un estudiante de la tabla derecha.");
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0) return;

        int idCurso = listaIdCursos.get(cboCurso.getSelectedIndex());
        String codigoEstudiante = tblAsig.getValueAt(fila, 0).toString();

        int r = JOptionPane.showConfirmDialog(this, "¿Desmatricular a este estudiante?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (r == JOptionPane.YES_OPTION) {
            if (new Controladores.Ctrl_Curso().quitarEstudiante(idCurso, codigoEstudiante)) {
                actualizarTablas();
            } else {
                JOptionPane.showMessageDialog(this, "Error al quitar.");
            }
        }
    }//GEN-LAST:event_btnQuitarActionPerformed

