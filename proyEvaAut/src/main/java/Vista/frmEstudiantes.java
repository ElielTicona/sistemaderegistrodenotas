    private void cargarMisCurs(String crisFiltro) {
        
        DefaultTableModel crisMod = new DefaultTableModel();
        crisMod.addColumn("ID CURSO");
        crisMod.addColumn("CURSO");
        crisMod.addColumn("SEMESTRE");
        tblCursosEst.setModel(crisMod); 

        tblCursosEst.getColumnModel().getColumn(0).setMaxWidth(0);
        tblCursosEst.getColumnModel().getColumn(0).setMinWidth(0);
        tblCursosEst.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);

        String crisSql = "SELECT c.id_curso, c.nombre_curso, c.semestre " +
                     "FROM cursos c " +
                     "INNER JOIN matricula m ON c.id_curso = m.id_curso " +
                     "WHERE m.dni_estudiante = ? AND c.nombre_curso LIKE ? AND c.estado = 1";
        System.out.println("Cargando cursos para: " + crisEstudLogueado.getUsername());
        try (java.sql.Connection crisCn = Conexion.Conexion.conectar();
             java.sql.PreparedStatement crisPst = crisCn.prepareStatement(crisSql)) {

            crisPst.setString(1, crisEstudLogueado.getUsername()); 
            crisPst.setString(2, "%" + crisFiltro + "%");
            
            java.sql.ResultSet crisRs = crisPst.executeQuery();

            while (crisRs.next()) {
                crisMod.addRow(new Object[]{
                    crisRs.getInt(1),
                    crisRs.getString(2),
                    crisRs.getString(3)
                });
            }
        } catch (Exception crisE) {
            System.out.println("Error al cargar cursos del estudiante: " + crisE.getMessage());
        }
    }
    
