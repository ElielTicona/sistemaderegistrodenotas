    private void calcularTotalRub() {
        try {
            double crisTotal = 0.0;
            crisTotal += Double.parseDouble(cboCrit1.getSelectedItem().toString());
            crisTotal += Double.parseDouble(cboCrit2.getSelectedItem().toString());
            crisTotal += Double.parseDouble(cboCrit3.getSelectedItem().toString());
            crisTotal += Double.parseDouble(cboCrit4.getSelectedItem().toString());
            txtTotalCrit.setText(String.format("%.2f", crisTotal));
        } catch (NumberFormatException | NullPointerException crisE) {
            txtTotalCrit.setText("0.00");
        }
    }
    
    private int procesarFilaRub(Controlador.CtrlRub crisCtrl, String crisNomCriterio, String crisPuntajeStr) {
        if (!crisNomCriterio.isEmpty()) {
            RubCrit crisCrit = new Modelo.RubCrit();
            crisCrit.setIdEval(crisIdEvalSeleccionada);
            crisCrit.setNomCriterio(crisNomCriterio);
            crisCrit.setDesc(crisNomCriterio); 
            crisCrit.setPuntajeMax(Double.parseDouble(crisPuntajeStr));

            if (crisCtrl.guardarCrit(crisCrit)) {
                return 1;
            }
        }
        return 0;
    }
    
    
    private void cargarCritRub() {
        Controlador.CtrlRub crisCtrlRubrica = new Controlador.CtrlRub();
        List<RubCrit> crisLista = crisCtrlRubrica.listarCrit(crisIdEvalSeleccionada);
        
        lblRub1.setText("N/A"); spin1.setEnabled(false); spin1.setValue(0.0);
        lblRub2.setText("N/A"); spin2.setEnabled(false); spin2.setValue(0.0);
        lblRub3.setText("N/A"); spin3.setEnabled(false); spin3.setValue(0.0);
        lblRub4.setText("N/A"); spin4.setEnabled(false); spin4.setValue(0.0);

        if (crisLista.size() > 0) configurarFilaEval(lblRub1, spin1, crisLista.get(0));
        if (crisLista.size() > 1) configurarFilaEval(lblRub2, spin2, crisLista.get(1));
        if (crisLista.size() > 2) configurarFilaEval(lblRub3, spin3, crisLista.get(2));
        if (crisLista.size() > 3) configurarFilaEval(lblRub4, spin4, crisLista.get(3));
    }

    private void configurarFilaEval(JLabel crisLbl, JSpinner crisSpin, RubCrit crisCrit) {
        crisLbl.setText(crisCrit.getNomCriterio());
        crisSpin.setModel(new javax.swing.SpinnerNumberModel(0.0, 0.0, crisCrit.getPuntajeMax(), 0.5));
        crisSpin.setEnabled(true);
    }
    
    private void calcularTotalEval() {
        double crisTotal = 0.0;
        if (spin1.isEnabled()) crisTotal += Double.parseDouble(spin1.getValue().toString());
        if (spin2.isEnabled()) crisTotal += Double.parseDouble(spin2.getValue().toString());
        if (spin3.isEnabled()) crisTotal += Double.parseDouble(spin3.getValue().toString());
        if (spin4.isEnabled()) crisTotal += Double.parseDouble(spin4.getValue().toString());
        
        txtTotNota.setText(String.format("%.2f", crisTotal).replace(",", "."));
    }
    
    private void reiniciarEvalRub() {
        JSpinner[] crisSpinners = {spin1, spin2, spin3, spin4};

        for (JSpinner crisSp : crisSpinners) {
            if (crisSp.isEnabled()) {
                crisSp.setValue(0.0);
            }
        }

        txtTotNota.setText("0.00");
    }
    
    private void cargarEvalCalif() {
        txtEval.removeAllItems();
        java.util.List<Modelo.Eval> crisLista = crisCtrlEval.listarPorCurso(crisIdCursoSelec);
        for (Modelo.Eval crisEv : crisLista) {
            if (crisEv.getTipo().equalsIgnoreCase("RUBRICA")) {
                txtEval.addItem(crisEv.getIdEval() + " - " + crisEv.getTitulo());
            }
        }
    }
    private void listarAlumCalif() {
        javax.swing.table.DefaultTableModel crisMod = (javax.swing.table.DefaultTableModel) tblAlumnosCal.getModel();
        crisMod.setRowCount(0);
        
        Controlador.CtrlCurso crisCtrlCurso = new Controlador.CtrlCurso();
        java.util.List<Object[]> crisAsig = crisCtrlCurso.listarAsignados(crisIdCursoSelec);
        
        for (Object[] crisEst : crisAsig) {
            crisMod.addRow(new Object[]{crisEst[0], crisEst[1], "Pendiente"}); 
        }
    }
    
