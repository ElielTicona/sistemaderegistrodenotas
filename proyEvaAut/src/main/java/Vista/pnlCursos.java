    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (crisIdEvalSeleccionada == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una evaluación de la tabla para editar");
            return;
        }

        String crisNom = txtNomEval.getText().trim();
        String crisTipo = cboTipo.getSelectedItem().toString();
        java.util.Date crisFechaSelect = jdFecha.getDate();

        if (crisNom.isEmpty() || crisFechaSelect == null) {
            JOptionPane.showMessageDialog(this, "Nombre y fecha son obligatorios");
            return;
        }

        String crisFechaFormateada = new java.text.SimpleDateFormat("yyyy-MM-dd").format(crisFechaSelect);

        Modelo.Eval crisEvEdit = new Modelo.Eval();
        crisEvEdit.setIdEval(crisIdEvalSeleccionada);
        crisEvEdit.setTitulo(crisNom);
        crisEvEdit.setTipo(crisTipo);
        crisEvEdit.setFechaExamen(crisFechaFormateada);

        if (crisCtrlEval.actualizar(crisEvEdit)) {
            JOptionPane.showMessageDialog(this, "Evaluación actualizada.");
            limpiarCampos();
            listarEval(); 
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar.");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

