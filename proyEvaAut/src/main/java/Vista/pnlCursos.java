    private void cargarCursDoc(int crisIdDocente) {
        cboCurso.removeAllItems();
        CtrlCurso crisCtrlCur = new CtrlCurso();
        List<Curso> crisListaCursos = crisCtrlCur.listarCursDoc(crisIdDocente);
        
        for (Curso crisCurso : crisListaCursos) {
            cboCurso.addItem(crisCurso.getIdCurso() + " - " + crisCurso.getNomCurso());
        }
    }
    
    private void listarEval() {
        DefaultTableModel crisMod = (DefaultTableModel) tblEval.getModel();
        crisMod.setRowCount(0); 

        List<Eval> crisLista = crisCtrlEval.listarPorCurso(crisIdCursoSelec);
        
        for (Eval crisEv : crisLista) {
            crisMod.addRow(new Object[]{
                crisEv.getIdEval(),
                crisEv.getTitulo(),
                crisEv.getTipo(),
                crisEv.getFechaExamen()
            });
        }
    }

