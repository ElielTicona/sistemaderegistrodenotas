    private void btnGuadNotaRubActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuadNotaRubActionPerformed
        if (crisDniAlumnoEvaluar.isEmpty() || crisIdEvalSeleccionada == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un alumno en la pestaña evaluación");
            return;
        }

        try {
            double crisNotaFinal = Double.parseDouble(txtTotNota.getText().replace(",", "."));

            Controlador.CtrlResult crisCtrlResult = new Controlador.CtrlResult();
            boolean crisOperacionExitosa = crisCtrlResult.guardarNotaRub(crisDniAlumnoEvaluar, crisIdEvalSeleccionada, crisNotaFinal);

            if (crisOperacionExitosa) {
                javax.swing.JOptionPane.showMessageDialog(this, "Calificación registrada con éxito");
                reiniciarEvalRub();
                crisDniAlumnoEvaluar = ""; 
                lblNombre.setText("INDICAR EL ALUMNO");
                listarResultFinal();    
                listarAlumCalif(); 
                jTabbedPane4.setSelectedIndex(3);

            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "La nota no se registró");
            }
        } catch (NumberFormatException crisE) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Verifique el formato de la nota");
        }
    }//GEN-LAST:event_btnGuadNotaRubActionPerformed

