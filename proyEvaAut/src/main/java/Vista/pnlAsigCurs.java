    private void cargarCombos() {
        crisListaIdCursos.clear();
        crisListaIdEsc.clear();
        cboCurso.removeAllItems();
        cboEscPro.removeAllItems();

        cboCurso.addItem("Seleccione Curso...");
        crisListaIdCursos.add(0);
        cboEscPro.addItem("Seleccione Escuela...");
        crisListaIdEsc.add(0);

        try (java.sql.Connection crisCn = Conexion.Conexion.conectar()) {
            java.sql.ResultSet crisRsC = crisCn.createStatement().executeQuery("SELECT id_curso, nombre_curso FROM cursos WHERE estado = 1");
            while (crisRsC.next()) {
                cboCurso.addItem(crisRsC.getString(2));
                crisListaIdCursos.add(crisRsC.getInt(1));
            }
            java.sql.ResultSet crisRsE = crisCn.createStatement().executeQuery("SELECT id_escuela, nombre_escuela FROM escuelas");
            while (crisRsE.next()) {
                cboEscPro.addItem(crisRsE.getString(2));
                crisListaIdEsc.add(crisRsE.getInt(1));
            }
        } catch (Exception crisE) {
            System.out.println("Error al cargar combos: " + crisE);
        }
    }

    private void actualizarTablas() {
        if (crisListaIdCursos.isEmpty() || crisListaIdEsc.isEmpty()) {
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0 || cboEscPro.getSelectedIndex() <= 0) {
            return; 
        }

        int crisIdCurso = crisListaIdCursos.get(cboCurso.getSelectedIndex());
        int crisIdEsc = crisListaIdEsc.get(cboEscPro.getSelectedIndex());
        String crisSemestre = cboSem.getSelectedItem().toString(); 

        Controlador.CtrlCurso crisCtrl = new Controlador.CtrlCurso();

        DefaultTableModel crisModIzq = new DefaultTableModel();
        crisModIzq.addColumn("CÓDIGO");
        crisModIzq.addColumn("ESTUDIANTE");
        tblPorAsignar.setModel(crisModIzq);
        
        List<Object[]> crisDisp = crisCtrl.listarEstudDisp(crisIdEsc, crisSemestre, crisIdCurso);
        for (Object[] crisFila : crisDisp) { crisModIzq.addRow(crisFila); }

        DefaultTableModel crisModDer = new DefaultTableModel();
        crisModDer.addColumn("CÓDIGO");
        crisModDer.addColumn("ESTUDIANTE");
        tblAsig.setModel(crisModDer);
        
        List<Object[]> crisAsig = crisCtrl.listarAsignados(crisIdCurso);
        for (Object[] crisFila : crisAsig) { crisModDer.addRow(crisFila); }
    }

