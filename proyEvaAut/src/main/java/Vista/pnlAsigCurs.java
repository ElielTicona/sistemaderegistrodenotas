    private void btnAsigTodosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAsigTodosActionPerformed
        if (tblPorAsignar.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No hay estudiantes para asignar.");
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0) return;

        int crisIdCurso = crisListaIdCursos.get(cboCurso.getSelectedIndex());
        Controlador.CtrlCurso crisCtrl = new Controlador.CtrlCurso();
        
        int crisExitos = 0;
        for (int crisI = 0; crisI < tblPorAsignar.getRowCount(); crisI++) {
            String crisCod = tblPorAsignar.getValueAt(crisI, 0).toString();
            if (crisCtrl.asignarEstud(crisIdCurso, crisCod)) {
                crisExitos++;
            }
        }
        JOptionPane.showMessageDialog(this, "Se asignaron " + crisExitos + " estudiantes al curso.");
        actualizarTablas();
    }//GEN-LAST:event_btnAsigTodosActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        int crisFila = tblPorAsignar.getSelectedRow();
        if (crisFila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un estudiante de la tabla izquierda.");
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0) return;

        int crisIdCurso = crisListaIdCursos.get(cboCurso.getSelectedIndex());
        String crisCodEstud = tblPorAsignar.getValueAt(crisFila, 0).toString();

        if (new Controlador.CtrlCurso().asignarEstud(crisIdCurso, crisCodEstud)) {
            actualizarTablas();
        } else {
            JOptionPane.showMessageDialog(this, "Error al asignar.");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        int crisFila = tblAsig.getSelectedRow();
        if (crisFila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un estudiante de la tabla derecha.");
            return;
        }
        if (cboCurso.getSelectedIndex() <= 0) return;

        int crisIdCurso = crisListaIdCursos.get(cboCurso.getSelectedIndex());
        String crisCodEstud = tblAsig.getValueAt(crisFila, 0).toString();

        int crisR = JOptionPane.showConfirmDialog(this, "¿Desmatricular a este estudiante?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (crisR == JOptionPane.YES_OPTION) {
            if (new Controlador.CtrlCurso().quitarEstud(crisIdCurso, crisCodEstud)) {
                actualizarTablas();
            } else {
                JOptionPane.showMessageDialog(this, "Error al quitar.");
            }
        }
    }//GEN-LAST:event_btnQuitarActionPerformed

