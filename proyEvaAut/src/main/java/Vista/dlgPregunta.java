    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String crisTextoPreg = txaPregunta.getText().trim();
        String crisOpA = txtA.getText().trim();
        String crisOpB = txtB.getText().trim();
        String crisOpC = txtC.getText().trim();
        String crisOpD = txtD.getText().trim();

        if (crisTextoPreg.isEmpty() || crisOpA.isEmpty() || crisOpB.isEmpty() || crisOpC.isEmpty() || crisOpD.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe llenar la pregunta y las 4 opciones.");
            return;
        }

        if (!rbA.isSelected() && !rbB.isSelected() && 
            !rbC.isSelected() && !rbD.isSelected()) {
            JOptionPane.showMessageDialog(this, "Debe marcar cuál de las opciones es la correcta.");
            return;
        }

        CtrlPreg crisControl = new CtrlPreg();
        Preg crisObjPreg = new Preg();
        crisObjPreg.setIdEval(this.crisIdEval);
        crisObjPreg.setTextoPreg(crisTextoPreg);
        crisObjPreg.setPuntajeMax(this.crisPuntajePorPreg);
        
        int crisIdGeneradoPreg = crisControl.guardarPreg(crisObjPreg);

        if (crisIdGeneradoPreg > 0) {
            guardarOpcBD(crisControl, crisIdGeneradoPreg, crisOpA, rbA.isSelected());
            guardarOpcBD(crisControl, crisIdGeneradoPreg, crisOpB, rbB.isSelected());
            guardarOpcBD(crisControl, crisIdGeneradoPreg, crisOpC, rbC.isSelected());
            guardarOpcBD(crisControl, crisIdGeneradoPreg, crisOpD, rbD.isSelected());
            
            JOptionPane.showMessageDialog(this, "Pregunta " + crisNroPregActual + " guardada.");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar la pregunta en BD.");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

