    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtCod.getText().isEmpty() || txtApeyNom.getText().isEmpty() || cboEscPro.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this, "Debe completar los campos");
            return;
        }
        Modelo.Estud crisEst = new Modelo.Estud();
        String crisCod = txtCod.getText().trim();

        crisEst.setCodUniv(crisCod);
        crisEst.setDni(crisCod); 
        crisEst.setNomCompleto(txtApeyNom.getText().trim().toUpperCase());
        crisEst.setIdEsc(crisListaIdEsc.get(cboEscPro.getSelectedIndex()));
        crisEst.setSemestre(cboSem.getSelectedItem().toString());

        if (new Controlador.CtrlEstud().guardar(crisEst)) {
            JOptionPane.showMessageDialog(this, "Estudiante registrado con éxito");
            cargarTabla("");
            estadoInicial();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (cboEscPro.getSelectedIndex() <= 0) {
             JOptionPane.showMessageDialog(this, "Seleccione una escuela válida");
             return;
        }
        CtrlEstud crisCtrl = new CtrlEstud();
        Estud crisEst = new Estud();

        crisEst.setDni(crisDniSelec);
        crisEst.setNomCompleto(txtApeyNom.getText().toUpperCase());
        crisEst.setIdEsc(crisListaIdEsc.get(cboEscPro.getSelectedIndex()));
        crisEst.setSemestre(cboSem.getSelectedItem().toString());

        if (crisCtrl.actualizar(crisEst)) {
            JOptionPane.showMessageDialog(this, "Registro actualizado con éxito");
            cargarTabla("");
            estadoInicial();
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void tblEstMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEstMouseClicked
        int crisFila = tblEst.getSelectedRow();
        if (crisFila >= 0) {
            String crisCod = tblEst.getValueAt(crisFila, 0).toString();
            crisDniSelec = tblEst.getValueAt(crisFila, 1).toString();
            String crisNoms = tblEst.getValueAt(crisFila, 2).toString();
            String crisIdEsc = tblEst.getValueAt(crisFila, 3).toString();
            String crisSem = tblEst.getValueAt(crisFila, 4).toString();

            txtCod.setText(crisCod);
            txtUser.setText(crisDniSelec);
            txtPass.setText(crisDniSelec); 
            txtApeyNom.setText(crisNoms);
            int crisIdEscBD = Integer.parseInt(crisIdEsc);
            int crisIndexCombo = crisListaIdEsc.indexOf(crisIdEscBD);
            if(crisIndexCombo != -1) {
                cboEscPro.setSelectedIndex(crisIndexCombo);
            }
            cboSem.setSelectedItem(crisSem); 

            btnGuardar.setEnabled(false);
            btnEdit.setEnabled(true);
            btnElim.setEnabled(true);
            
        }
    }//GEN-LAST:event_tblEstMouseClicked

    private void btnElimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnElimActionPerformed
        if (crisDniSelec.isEmpty()) return;

        int crisR = JOptionPane.showConfirmDialog(this, "¿Eliminar al estudiante con código " + crisDniSelec + "?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (crisR == JOptionPane.YES_OPTION) {
            if (new CtrlEstud().eliminar(crisDniSelec)) {
                JOptionPane.showMessageDialog(this, "Estudiante dado de baja.");
                cargarTabla("");
                estadoInicial();
            }
        }
    }//GEN-LAST:event_btnElimActionPerformed

