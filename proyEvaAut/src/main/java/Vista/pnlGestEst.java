    private void estadoInicial() {
        crisDniSelec = "";
        limpiarCampos();
        btnGuardar.setEnabled(true);  
        btnEdit.setEnabled(false);    
        btnElim.setEnabled(false);    
        txtCod.requestFocus();
    }

    private void limpiarCampos() {
        txtCod.setText("");
        txtApeyNom.setText("");
        cboEscPro.setSelectedIndex(0);
        cboSem.setSelectedIndex(0);
        txtUser.setText("");
        txtPass.setText("");
    }

    private void cargarTabla(String crisValor) {
        DefaultTableModel crisMod = new DefaultTableModel();
        crisMod.addColumn("COD. UNIV");
        crisMod.addColumn("DNI");
        crisMod.addColumn("NOMBRES");
        crisMod.addColumn("ID_ESC");
        crisMod.addColumn("SEMESTRE");
        tblEst.setModel(crisMod);
        tblEst.getColumnModel().getColumn(3).setMaxWidth(0);
        tblEst.getColumnModel().getColumn(3).setMinWidth(0);
        tblEst.getTableHeader().getColumnModel().getColumn(3).setMaxWidth(0);

        CtrlEstud crisCtrl = new CtrlEstud();
        List<Estud> crisLista = crisCtrl.listarEstud(crisValor); 

        for (Estud crisE : crisLista) {
            crisMod.addRow(new Object[]{
                crisE.getCodUniv(),
                crisE.getDni(),
                crisE.getNomCompleto(),
                crisE.getIdEsc(), 
                crisE.getSemestre()
            });
        }
    }
    
    private void cargarCombos() {
        crisListaIdEsc.clear();
        cboEscPro.removeAllItems();
        cboEscPro.addItem("Seleccione Escuela...");
        crisListaIdEsc.add(0);

        try (java.sql.Connection crisCn = Conexion.Conexion.conectar();
             java.sql.Statement crisSt = crisCn.createStatement();
             java.sql.ResultSet crisRsE = crisSt.executeQuery("SELECT id_escuela, nombre_escuela FROM escuelas WHERE estado = 1")) {
            
            while (crisRsE.next()) {
                cboEscPro.addItem(crisRsE.getString("nombre_escuela"));
                crisListaIdEsc.add(crisRsE.getInt("id_escuela"));
            }
        } catch (Exception crisE) {
            System.out.println("Error al cargar combo de escuelas en estudiantes: " + crisE.getMessage());
        }
    }
