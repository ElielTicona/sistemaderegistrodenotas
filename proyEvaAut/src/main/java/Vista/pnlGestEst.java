    private void txtSubirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSubirActionPerformed
        String crisRuta = txtRuta.getText().trim();
        
        if (crisRuta.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un archivo de Excel antes de subir.");
            return;
        }
        CtrlEstud crisCtrl = new CtrlEstud();

        int[] crisResult = crisCtrl.importarExcel(crisRuta);

        JOptionPane.showMessageDialog(this, 
            "Proceso terminado.\n" +
            "Estudiantes registrados: " + crisResult[0] + "\n" +
            "Errores o Duplicados: " + crisResult[1] + "\n\n" +
            "Nota: Se usó el Código como Usuario y Password.");

        cargarTabla("");
        txtRuta.setText("");
        estadoInicial();
    }//GEN-LAST:event_txtSubirActionPerformed

