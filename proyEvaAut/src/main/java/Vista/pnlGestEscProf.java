    private void estadoInicial() {
        crisIdEscSeleccionada = 0;
        txtNombre.setText(""); 
        btnGuardar.setEnabled(true);
        btnEdit.setEnabled(false);
        btnElim.setEnabled(false);
        txtNombre.requestFocus();
    }
    
    private void cargarTabla() {
        DefaultTableModel crisMod = new DefaultTableModel();
        crisMod.addColumn("ID");
        crisMod.addColumn("ESCUELA PROFESIONAL");
        tblEP.setModel(crisMod);
        tblEP.getColumnModel().getColumn(0).setMaxWidth(0);
        tblEP.getColumnModel().getColumn(0).setMinWidth(0);
        tblEP.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);

        CtrlEsc crisCtrl = new CtrlEsc();
        List<Escuela> crisLista = crisCtrl.consultarEsc();

        for (Modelo.Escuela crisE : crisLista) {
            crisMod.addRow(new Object[]{
                crisE.getIdEsc(),
                crisE.getNomEsc()
            });
        }
    }
