    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el nombre de la Escuela Profesional.");
            return;
        }

        Escuela crisEsc = new Escuela();
        crisEsc.setNomEsc(txtNombre.getText().trim().toUpperCase());

        if (new Controlador.CtrlEsc().guardar(crisEsc)) {
            JOptionPane.showMessageDialog(this, "Escuela registrada con éxito.");
            cargarTabla();
            estadoInicial();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (crisIdEscSeleccionada == 0 || txtNombre.getText().trim().isEmpty()) return;

        Escuela crisEsc = new Escuela();
        crisEsc.setIdEsc(crisIdEscSeleccionada);
        crisEsc.setNomEsc(txtNombre.getText().trim().toUpperCase());

        if (new CtrlEsc().actualizar(crisEsc)) {
            JOptionPane.showMessageDialog(this, "Escuela actualizada correctamente.");
            cargarTabla();
            estadoInicial();
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnElimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnElimActionPerformed
        if (crisIdEscSeleccionada == 0) return;

        int crisR = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar esta Escuela? \nNota: No se podrá borrar si ya tiene alumnos registrados.", "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);
        
        if (crisR == JOptionPane.YES_OPTION) {
            if (new Controlador.CtrlEsc().eliminar(crisIdEscSeleccionada)) {
                JOptionPane.showMessageDialog(this, "Escuela eliminada.");
                cargarTabla();
                estadoInicial();
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar. Es probable que esta escuela ya tenga estudiantes o cursos asignados.", "Error de Integridad", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnElimActionPerformed

    private void tblEPMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEPMouseClicked
        int crisFila = tblEP.getSelectedRow();
        if (crisFila >= 0) {
            // Se convierte el índice por si la tabla está filtrada por el buscador
            int crisFilaModel = tblEP.convertRowIndexToModel(crisFila);
            
            crisIdEscSeleccionada = Integer.parseInt(tblEP.getModel().getValueAt(crisFilaModel, 0).toString());
            txtNombre.setText(tblEP.getModel().getValueAt(crisFilaModel, 1).toString());

            btnGuardar.setEnabled(false);
            btnEdit.setEnabled(true);
            btnElim.setEnabled(true);
        }
    }//GEN-LAST:event_tblEPMouseClicked

    private void txtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyReleased
        DefaultTableModel crisMod = (DefaultTableModel) tblEP.getModel();
        TableRowSorter<DefaultTableModel> crisTrs = new TableRowSorter<>(crisMod);
        tblEP.setRowSorter(crisTrs);
        crisTrs.setRowFilter(RowFilter.regexFilter("(?i)" + txtBuscar.getText().trim()));
    }//GEN-LAST:event_txtBuscarKeyReleased


