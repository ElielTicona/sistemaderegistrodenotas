    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txtUser.getText().isEmpty() || txtPass.getText().isEmpty() || txtNomyApe.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos obligatorios.");
            return;
        }

        Modelo.Usu crisU = new Modelo.Usu();
        crisU.setUsername(txtUser.getText().trim());
        crisU.setPassword(txtPass.getText().trim());
        crisU.setNomCompleto(txtNomyApe.getText().trim().toUpperCase());
        crisU.setRol(cboRol.getSelectedItem().toString());

        if (new Controlador.CtrlUsu().guardar(crisU)) {
            JOptionPane.showMessageDialog(this, "Usuario registrado con éxito.");
            cargarTabla("");
            estadoInicial();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (crisIdUsuSelec == 0) return;

        Modelo.Usu crisU = new Modelo.Usu();
        crisU.setIdUsu(crisIdUsuSelec);
        crisU.setUsername(txtUser.getText().trim());
        crisU.setPassword(txtPass.getText().trim());
        crisU.setNomCompleto(txtNomyApe.getText().trim().toUpperCase());
        crisU.setRol(cboRol.getSelectedItem().toString());

        if (new Controlador.CtrlUsu().actualizar(crisU)) {
            JOptionPane.showMessageDialog(this, "Usuario actualizado.");
            cargarTabla("");
            estadoInicial();
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (crisIdUsuSelec == 0) return;

        int crisR = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este usuario?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (crisR == JOptionPane.YES_OPTION) {
            if (new Controlador.CtrlUsu().eliminar(crisIdUsuSelec)) {
                JOptionPane.showMessageDialog(this, "Usuario eliminado");
                cargarTabla("");
                estadoInicial();
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void txtBuscarKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBuscarKeyPressed
        DefaultTableModel crisMod = (DefaultTableModel) tblUser.getModel();
        TableRowSorter<DefaultTableModel> crisTrs = new TableRowSorter<>(crisMod);
        tblUser.setRowSorter(crisTrs);
        crisTrs.setRowFilter(RowFilter.regexFilter("(?i)" + txtBuscar.getText().trim()));
    }//GEN-LAST:event_txtBuscarKeyPressed


