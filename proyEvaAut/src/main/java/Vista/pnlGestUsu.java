    private void estadoInicial() {
        crisIdUsuSelec = 0;
        txtDni.setText("");
        txtNomyApe.setText("");
        txtUser.setText("");
        txtPass.setText("");
        cboRol.setSelectedIndex(0);
        btnGuardar.setEnabled(true);
        btnEditar.setEnabled(false);
        btnEliminar.setEnabled(false);
        txtDni.requestFocus();
    }
    
    private void cargarTabla(String crisValor) {
        DefaultTableModel crisMod = new DefaultTableModel();
        crisMod.addColumn("ID");
        crisMod.addColumn("DNI/USER");
        crisMod.addColumn("NOMBRES");
        crisMod.addColumn("ROL");
        crisMod.addColumn("PASS_OCULTO");
        tblUser.setModel(crisMod);
        tblUser.getColumnModel().getColumn(0).setMaxWidth(0);
        tblUser.getColumnModel().getColumn(0).setMinWidth(0);
        tblUser.getTableHeader().getColumnModel().getColumn(0).setMaxWidth(0);
        
        tblUser.getColumnModel().getColumn(4).setMaxWidth(0);
        tblUser.getColumnModel().getColumn(4).setMinWidth(0);
        tblUser.getTableHeader().getColumnModel().getColumn(4).setMaxWidth(0);

        Controlador.CtrlUsu crisCtrl = new Controlador.CtrlUsu();
        List<Modelo.Usu> crisLista = crisCtrl.listarUsuGest();

        for (Modelo.Usu crisU : crisLista) {
            if(crisU.getNomCompleto().toLowerCase().contains(crisValor.toLowerCase()) || 
               crisU.getUsername().contains(crisValor)) {
                
                crisMod.addRow(new Object[]{
                    crisU.getIdUsu(),
                    crisU.getUsername(),
                    crisU.getNomCompleto(),
                    crisU.getRol(),
                    crisU.getPassword()
                });
            }
        }
    }
