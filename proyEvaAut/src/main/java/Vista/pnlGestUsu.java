    private void tblUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUserMouseClicked
        int crisFila = tblUser.getSelectedRow();
        if (crisFila >= 0) {
            int crisFilaModel = tblUser.convertRowIndexToModel(crisFila);
            
            crisIdUsuSelec = Integer.parseInt(tblUser.getModel().getValueAt(crisFilaModel, 0).toString());
            txtDni.setText(tblUser.getModel().getValueAt(crisFilaModel, 1).toString());
            txtUser.setText(tblUser.getModel().getValueAt(crisFilaModel, 1).toString());
            txtNomyApe.setText(tblUser.getModel().getValueAt(crisFilaModel, 2).toString());
            cboRol.setSelectedItem(tblUser.getModel().getValueAt(crisFilaModel, 3).toString());
            txtPass.setText(tblUser.getModel().getValueAt(crisFilaModel, 4).toString());

            btnGuardar.setEnabled(false);
            btnEditar.setEnabled(true);
            btnEliminar.setEnabled(true);
        }
    }//GEN-LAST:event_tblUserMouseClicked

