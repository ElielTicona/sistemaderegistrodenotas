public class Estud {
    private String crisDni;
    private String crisNomCompleto;
    private String crisCodUniv;
    private int crisIdEsc;
    private String crisSemestre;
    private int crisIdUsu;
    private int crisEstado;

    public Estud() {}

    public String getDni() {
        return crisDni;
    }

    public void setDni(String crisDni) {
        this.crisDni = crisDni;
    }

    public String getNomCompleto() {
        return crisNomCompleto;
    }

    public void setNomCompleto(String crisNomCompleto) {
        this.crisNomCompleto = crisNomCompleto;
    }


    public String getCodUniv() {
        return crisCodUniv;
    }

    public void setCodUniv(String crisCodUniv) {
        this.crisCodUniv = crisCodUniv;
    }

    public int getIdEsc() {
        return crisIdEsc;
    }

    public void setIdEsc(int crisIdEsc) {
        this.crisIdEsc = crisIdEsc;
    }

    public String getSemestre() {
        return crisSemestre;
    }

    public void setSemestre(String crisSemestre) {
        this.crisSemestre = crisSemestre;
    }

    public int getIdUsu() {
        return crisIdUsu;
    }

    public void setIdUsu(int crisIdUsu) {
        this.crisIdUsu = crisIdUsu;
    }

    public int getEstado() {
        return crisEstado;
    }

    public void setEstado(int crisEstado) {
        this.crisEstado = crisEstado;
    }

    
    
    
    
}
